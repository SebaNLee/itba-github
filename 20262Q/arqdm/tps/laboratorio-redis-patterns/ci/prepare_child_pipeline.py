#!/usr/bin/env python3
"""Discover changed services vs the default branch and emit a child GitLab CI YAML."""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path


def list_service_names(services_root: Path) -> list[str]:
    if not services_root.is_dir():
        return []
    return sorted(
        p.name
        for p in services_root.iterdir()
        if p.is_dir() and not p.name.startswith(".")
    )


def select_services(
    *,
    all_services: list[str],
    is_default_branch: bool,
    bootstrap_first_commit: bool,
    changed_paths: list[str],
) -> list[str]:
    """Return service names to build (see specs/01-gitlab-service-ci.md, monorepo path rules)."""
    if bootstrap_first_commit or is_default_branch:
        return list(all_services)

    shared = (
        ".gitlab-ci.yml",
        "ci/",
        "tests/",
        "specs/",
    )
    for line in changed_paths:
        if line == shared[0] or line.startswith(shared[1:]):
            return list(all_services)

    allowed = set(all_services)
    seen: set[str] = set()
    prefix = "services/"
    for line in changed_paths:
        if not line.startswith(prefix):
            continue
        rest = line[len(prefix) :]
        name = rest.split("/")[0] if rest else ""
        if name in allowed:
            seen.add(name)
    return sorted(seen)


def _is_default_branch_env(environ: dict[str, str], default_branch: str) -> bool:
    commit_branch = environ.get("CI_COMMIT_BRANCH", "")
    if commit_branch and commit_branch == default_branch:
        return True
    # Push pipelines: ref name is the branch name
    ref = environ.get("CI_COMMIT_REF_NAME", "")
    if ref == default_branch:
        return True
    # MR targeting default branch: still run selection by diff (not "on" default branch)
    return False


def _bootstrap_first_commit(environ: dict[str, str]) -> bool:
    return (
        environ.get("CI_COMMIT_BEFORE_SHA", "")
        == "0000000000000000000000000000000000000000"
    )


def _git_changed_paths(repo: Path, default_branch: str) -> list[str]:
    ref = f"origin/{default_branch}"
    r = subprocess.run(
        ["git", "diff", "--name-only", f"{ref}...HEAD"],
        cwd=repo,
        text=True,
        capture_output=True,
        check=False,
    )
    if r.returncode != 0:
        print(r.stderr, file=sys.stderr)
        r.check_returncode()
    lines = [ln.strip() for ln in r.stdout.splitlines() if ln.strip()]
    return lines


def _git_fetch_default(repo: Path, default_branch: str) -> None:
    subprocess.run(
        ["git", "fetch", "origin", default_branch, "--depth=500"],
        cwd=repo,
        check=True,
    )


def render_child_pipeline(services: list[str]) -> str:
    """Minimal child pipeline: same build/test contract as the former parent matrix."""
    header = [
        "# Generated by ci/prepare_child_pipeline.py — do not edit.",
        "variables:",
        '  DOCKER_TLS_CERTDIR: "/certs"',
        "",
        ".docker-dind:",
        "  image: docker:24-cli",
        "  services:",
        "    - docker:24-dind",
        "  before_script:",
        "    - until docker info; do sleep 2; done",
        "",
        "workflow:",
        "  rules:",
        "    - when: always",
        "",
    ]

    if not services:
        lines = [
            *header,
            "stages:",
            "  - build",
            "",
            '"no-service-changes":',
            "  stage: build",
            "  image: alpine:3.20",
            "  script:",
            '    - echo "No Docker service jobs (nothing under services/ changed vs default branch, and no shared CI/spec paths)."',
            "",
        ]
        return "\n".join(lines) + "\n"

    lines = [
        *header,
        "stages:",
        "  - build",
        "  - test",
        "",
    ]

    for svc in services:
        q = json.dumps
        lines.extend(
            [
                f"{q(f'build:{svc}')}:",
                "  extends:",
                "    - .docker-dind",
                "  stage: build",
                "  variables:",
                f"    SERVICE: {q(svc)}",
                "  script:",
                '    - cd "services/${SERVICE}"',
                "    - docker compose run --rm builder",
                "    - docker compose build test",
                "    - |",
                "      set -euo pipefail",
                '      to_save=""',
                "      for img in $(docker compose config --images | sort -u); do",
                '        if docker image inspect "$img" >/dev/null 2>&1; then',
                '          to_save="$to_save $img"',
                "        fi",
                "      done",
                '      if [ -z "${to_save// }" ]; then',
                '        echo "build (${SERVICE}): no compose images on daemon after builder" >&2',
                "        docker images",
                "        exit 1",
                "      fi",
                '      docker save -o "$CI_PROJECT_DIR/${SERVICE}-images.tar" $to_save',
                "  artifacts:",
                f"    name: {q(f'{svc}-images')}",
                "    paths:",
                f"      - {q(f'{svc}-images.tar')}",
                "    expire_in: 1 hour",
                "",
            ]
        )

    for svc in services:
        q = json.dumps
        b = q(f"build:{svc}")
        lines.extend(
            [
                f"{q(f'test:{svc}')}:",
                "  extends:",
                "    - .docker-dind",
                "  stage: test",
                "  needs:",
                f"    - job: {b}",
                "      artifacts: true",
                "  variables:",
                f"    SERVICE: {q(svc)}",
                "  script:",
                '    - docker load -i "${SERVICE}-images.tar"',
                '    - cd "services/${SERVICE}"',
                "    - docker compose run --rm test",
                "",
            ]
        )

    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--repo",
        type=Path,
        default=Path.cwd(),
        help="Git repository root (default: cwd)",
    )
    args = parser.parse_args()

    repo: Path = args.repo.resolve()
    env = dict(os.environ)
    default_branch = env.get("CI_DEFAULT_BRANCH", "main")

    all_names = list_service_names(repo / "services")
    is_default = _is_default_branch_env(env, default_branch)
    bootstrap = _bootstrap_first_commit(env)

    changed: list[str] = []
    if not bootstrap and not is_default:
        _git_fetch_default(repo, default_branch)
        changed = _git_changed_paths(repo, default_branch)

    selected = select_services(
        all_services=all_names,
        is_default_branch=is_default,
        bootstrap_first_commit=bootstrap,
        changed_paths=changed,
    )

    args.output.write_text(
        render_child_pipeline(selected),
        encoding="utf-8",
    )
    print("Selected services:", ", ".join(selected) if selected else "(none)")


if __name__ == "__main__":
    main()
